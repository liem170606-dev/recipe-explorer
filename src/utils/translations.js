export function translateInstructions(meal) {
  if (!meal) return []
  const key = meal.strMeal ? meal.strMeal.toLowerCase().trim() : ''

  if (mealInstructionsTranslations[key]) {
    return mealInstructionsTranslations[key]
  }

  // במידה ומדובר במתכון חדש שהמשתמש חיפש, חלוקה לפסקאות
  if (meal.strInstructions) {
    return meal.strInstructions
      .split(/\r?\n/)
      .map((line) => line.trim())
      .filter((line) => line.length > 0)
  }

  return []
}

